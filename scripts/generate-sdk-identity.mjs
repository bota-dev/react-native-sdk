import { readFileSync, writeFileSync } from 'node:fs';

const manifest = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const target = new URL('../src/sdkIdentity.ts', import.meta.url);
const expected = `// Generated by scripts/generate-sdk-identity.mjs from package.json.\nexport const SDK_PACKAGE = ${JSON.stringify(manifest.name)};\nexport const SDK_VERSION = ${JSON.stringify(manifest.version)};\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== expected) throw new Error('SDK identity drift: run npm run identity:generate');
} else {
  writeFileSync(target, expected);
}
